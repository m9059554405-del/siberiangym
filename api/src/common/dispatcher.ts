// P3.18: в PM2-кластере фоновые задачи (диспетчер напоминалок P2.4,
// просрочка заказов P0.2, догенерация серий P2.12) должны выполняться
// ровно в одном воркере — иначе N копий продублируют одни и те же тики.
// PM2 выставляет каждому воркеру NODE_APP_INSTANCE (0,1,2,...): диспетчером
// назначается воркер 0. Вне PM2 (dev, одиночный контейнер) переменной нет —
// работает как раньше, задачи выполняет единственный процесс.
// Отказ воркера-диспетчера не теряет работу надолго: PM2 перезапускает его
// за секунды, а сами задачи идемпотентны (уникальность уведомлений
// kind+refId+clientId, идемпотентная просрочка/догенерация).
export function isDispatcherInstance(): boolean {
  const id = process.env.NODE_APP_INSTANCE;
  return id === undefined || id === '0';
}
