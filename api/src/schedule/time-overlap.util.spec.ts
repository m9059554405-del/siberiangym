import { overlaps } from './time-overlap.util';

// P3.1: пересечение интервалов расписания (P2.7) — сравнение по строкам
// HH:MM в пределах одного календарного дня, занятия через полночь не
// существуют.

const sep14 = (start: string, end: string) => ({ date: new Date('2026-09-14T00:00:00.000Z'), start, end });
const sep15 = (start: string, end: string) => ({ date: new Date('2026-09-15T00:00:00.000Z'), start, end });

describe('overlaps', () => {
  it('частичное пересечение в один день', () => {
    expect(overlaps(sep14('10:00', '12:00'), sep14('11:00', '13:00'))).toBe(true);
  });

  it('полное вложение', () => {
    expect(overlaps(sep14('10:00', '12:00'), sep14('10:30', '11:30'))).toBe(true);
  });

  it('совпадающие границы — не пересечение (конец = начало соседнего)', () => {
    expect(overlaps(sep14('10:00', '11:00'), sep14('11:00', '12:00'))).toBe(false);
  });

  it('разные дни — не пересечение, даже при одинаковом времени', () => {
    expect(overlaps(sep14('10:00', '12:00'), sep15('10:00', '12:00'))).toBe(false);
  });

  it('непересекающиеся интервалы одного дня', () => {
    expect(overlaps(sep14('08:00', '09:00'), sep14('10:00', '12:00'))).toBe(false);
  });

  it('дата с временем внутри дня не влияет (сравнивается календарный день)', () => {
    expect(overlaps({ date: new Date('2026-09-14T23:59:00.000Z'), start: '10:00', end: '11:00' }, sep14('10:30', '11:30'))).toBe(true);
  });
});
